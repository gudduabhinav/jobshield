export function getDemoJobs(): JobRecord[] {
  const jobs: JobRecord[] = rawJobs.map((raw, index) => {
    const id = `job-demo-${index + 1}`;
    const now = new Date().toISOString();
    const skills = raw.skills ? raw.skills.split(',').map(s => s.trim()) : [];

    return {
      id,
      title: raw.title,
      companyName: raw.companyName,
      location: raw.location,
      description: raw.description,
      salary: raw.salary || null,
      employmentType: raw.employmentType || null,
      experienceRequired: null,
      postedDate: raw.postedDate || null,
      applicationUrl: raw.applicationUrl,
      companyUrl: raw.companyUrl || null,
      sourceUrl: raw.sourceUrl || null,
      sourceName: raw.sourceName || 'unknown',
      skills,
      remoteStatus: raw.remoteStatus || null,
      scrapedAt: now,
      riskScore: 0,
      riskLevel: 'LOW',
      riskReasons: [],
      duplicateGroupId: null,
      isReposted: false,
    };
  });

  const withRisk = jobs.map(job => {
    const assessment = calculateRiskScore({
      title: job.title,
      companyName: job.companyName,
      description: job.description,
      applicationUrl: job.applicationUrl,
      companyUrl: job.companyUrl,
      salary: job.salary,
      isReposted: job.isReposted,
      duplicateGroupId: job.duplicateGroupId,
    });
    return {
      ...job,
      riskScore: assessment.score,
      riskLevel: assessment.level,
      riskReasons: assessment.reasons,
    };
  });

  return annotateDuplicates(withRisk);
}

