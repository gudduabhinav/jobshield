export function getDashboardStats() {
  const jobs = getDemoJobs();
  const total = jobs.length;
  const low = jobs.filter(j => j.riskLevel === 'LOW').length;
  const medium = jobs.filter(j => j.riskLevel === 'MEDIUM').length;
  const high = jobs.filter(j => j.riskLevel === 'HIGH').length;

  const jobsOverTime = Array.from({ length: 14 }, (_, i) => {
    const date = new Date();
    date.setDate(date.getDate() - (13 - i));
    const base = 80 + Math.floor(Math.random() * 30);
    return {
      date: date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
      count: base + Math.floor(i * 3),
    };
  });

  const extractionQuality = Array.from({ length: 14 }, (_, i) => {
    const date = new Date();
    date.setDate(date.getDate() - (13 - i));
    let quality = 96 + Math.random() * 4;
    if (i === 5) quality = 12;
    if (i === 6) quality = 89;
    return {
      date: date.toLocaleDateString('en-US', { month: 'short', day: 'numeric' }),
      quality: Math.round(quality * 10) / 10,
    };
  });

  return {
    totalJobs: total,
    lowRisk: low,
    mediumRisk: medium,
    highRisk: high,
    scraperStatus: 'HEALTHY' as const,
    lastSuccessfulRun: new Date(Date.now() - 300000).toISOString(),
    healingEvents: 3,
    recoveryRate: 100,
    jobsOverTime,
    riskDistribution: [
      { level: 'Low Risk', count: low },
      { level: 'Medium Risk', count: medium },
      { level: 'High Risk', count: high },
    ],
    extractionQuality,
  };
}
